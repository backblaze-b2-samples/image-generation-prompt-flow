import { GoogleGenAI, Modality } from "@google/genai";
import type { GenerateResult } from "./types";
import { getModelConfig } from "@/lib/models";
import { getImageDimensions } from "./image-utils";

export async function generateGeminiImage(
  modelId: string,
  prompt: string
): Promise<GenerateResult> {
  const startTime = Date.now();
  const apiKey = process.env.GOOGLE_AI_API_KEY;

  if (!apiKey) {
    throw new Error("GOOGLE_AI_API_KEY is not set");
  }

  const config = getModelConfig(modelId);

  if (config?.type === "multimodal") {
    return generateWithMultimodal(modelId, prompt, apiKey, startTime);
  } else {
    return generateWithImagen(modelId, prompt, apiKey, startTime);
  }
}

async function generateWithMultimodal(
  modelId: string,
  prompt: string,
  apiKey: string,
  startTime: number
): Promise<GenerateResult> {
  const client = new GoogleGenAI({ apiKey });

  const response = await client.models.generateContent({
    model: modelId,
    contents: `Generate an image: ${prompt}`,
    config: {
      responseModalities: [Modality.TEXT, Modality.IMAGE],
      imageConfig: {
        aspectRatio: "1:1",
        imageSize: "2K",
      },
    } as Record<string, unknown>,
  });

  const parts = response.candidates?.[0]?.content?.parts || [];

  for (const part of parts) {
    if (part.inlineData) {
      const imageBuffer = Buffer.from(part.inlineData.data || "", "base64");
      const { width, height } = getImageDimensions(imageBuffer);
      return {
        imageBuffer,
        mime: part.inlineData.mimeType || "image/png",
        width,
        height,
        latencyMs: Date.now() - startTime,
      };
    }
  }

  throw new Error("No image generated by Gemini multimodal");
}

async function generateWithImagen(
  modelId: string,
  prompt: string,
  apiKey: string,
  startTime: number
): Promise<GenerateResult> {
  const client = new GoogleGenAI({ apiKey });

  const response = await client.models.generateImages({
    model: modelId,
    prompt,
    config: {
      numberOfImages: 1,
      aspectRatio: "1:1",
      sampleImageSize: "2K",
      outputOptions: {
        mimeType: "image/png",
      },
    } as Record<string, unknown>,
  });

  const images = response.generatedImages;
  if (!images || images.length === 0) {
    throw new Error("No image generated by Imagen");
  }

  const imageData = images[0].image?.imageBytes;
  if (!imageData) {
    throw new Error("No image data in Imagen response");
  }

  const imageBuffer = Buffer.from(imageData, "base64");
  const { width, height } = getImageDimensions(imageBuffer);

  return {
    imageBuffer,
    mime: "image/png",
    width,
    height,
    latencyMs: Date.now() - startTime,
  };
}
