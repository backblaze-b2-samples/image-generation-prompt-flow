"use client";

import { useImageUrl } from "@/hooks/use-generations";
import { Loader2, ImageOff, AlertCircle } from "lucide-react";

interface ImageDisplayProps {
  b2Key: string | undefined;
  status: string;
  modelId: string;
}

export function ImageDisplay({ b2Key, status, modelId }: ImageDisplayProps) {
  const { url, isLoading: isLoadingUrl } = useImageUrl(b2Key);

  // Show loading state
  if (status === "running" || status === "pending") {
    return (
      <div className="flex flex-col items-center justify-center h-full text-muted-foreground">
        <Loader2 className="w-8 h-8 animate-spin mb-2" />
        <p className="text-sm">
          {status === "running" ? "Generating..." : "Waiting..."}
        </p>
      </div>
    );
  }

  // Show error state
  if (status === "failed") {
    return (
      <div className="flex flex-col items-center justify-center h-full text-destructive">
        <AlertCircle className="w-8 h-8 mb-2" />
        <p className="text-sm">Generation failed</p>
      </div>
    );
  }

  // Show loading URL state
  if (isLoadingUrl || (b2Key && !url)) {
    return (
      <div className="flex flex-col items-center justify-center h-full text-muted-foreground">
        <Loader2 className="w-8 h-8 animate-spin mb-2" />
        <p className="text-sm">Loading image...</p>
      </div>
    );
  }

  // Show no image state
  if (!url) {
    return (
      <div className="flex flex-col items-center justify-center h-full text-muted-foreground">
        <ImageOff className="w-8 h-8 mb-2" />
        <p className="text-sm">No image available</p>
      </div>
    );
  }

  // Show image
  return (
    <div className="relative h-full">
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={url}
        alt={`Generated by ${modelId}`}
        className="w-full h-full object-contain"
      />
    </div>
  );
}
